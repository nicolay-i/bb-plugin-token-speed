import { build } from "esbuild";
import { writeFile } from "node:fs/promises";

// BB emits one app bundle, so inline a separately bundled, SDK-independent worker.
const result = await build({ entryPoints: ["tokenizer-worker.ts"], bundle: true, minify: true,
  platform: "browser", format: "iife", write: false });
await writeFile("worker-source.generated.ts", `// Generated by build-worker.mjs; do not edit.\nexport default ${JSON.stringify(result.outputFiles[0].text)};\n`);
